func T(lang, key string, args ...interface{}) string {
	if m, ok := Messages[lang]; ok {
		if msg, ok := m[key]; ok {
			if len(args) > 0 {
				return fmt.Sprintf(msg, args...)
			}
			return msg
		}
	}
	// fallback to English
	if msg, ok := Messages["en"][key]; ok {
		if len(args) > 0 {
			return fmt.Sprintf(msg, args...)
		}
		return msg
	}
	return key
}
